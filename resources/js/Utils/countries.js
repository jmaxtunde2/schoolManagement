export const countries = Object.entries(COUNTRY_NAMES)
    .map(([code, name]) => ({ code, name }))
    .sort((a, b) => a.name.localeCompare(b.name, 'fr'));

const COUNTRIES_BY_NAME = new Map(countries.map((country) => [country.name, country]));

/** Retrouve un pays à partir de son libellé (tolérant aux accents/casse). */
export function findCountryByName(name) {
    return COUNTRIES_BY_NAME.get(name) ?? null;
}

/** Construit l'émoji drapeau à partir du code ISO 3166-1 alpha-2. */
export function flagEmoji(code) {
    if (typeof code !== 'string' || code.length !== 2) {
        return '';
    }

    return String.fromCodePoint(
        ...code
            .toUpperCase()
            .split('')
            .map((char) => 0x1f1e6 + char.charCodeAt(0) - 65)
    );
}
